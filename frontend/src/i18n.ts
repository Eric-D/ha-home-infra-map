const TABLES: Record<string, Record<I18nKey, string>> = { fr, en };

export function langOf(hass: Hass | undefined): string {
  const raw = hass?.locale?.language ?? hass?.language ?? (typeof navigator !== 'undefined' ? navigator.language : 'fr');
  return String(raw || 'fr').split('-')[0].toLowerCase() === 'fr' ? 'fr' : 'en';
}

export type Translate = (key: I18nKey | string, params?: Record<string, unknown>) => string;

export function translator(lang: string): Translate {
  const table = TABLES[lang] ?? en;
  return (key, params) => {
    let text = (table as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) text = text.split(`{${k}}`).join(v === null || v === undefined ? '?' : String(v));
    }
    return text;
  };
}

